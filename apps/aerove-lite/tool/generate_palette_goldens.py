"""Reproduce Standard surface goldens from pinned local Dart inputs without downloads."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

STANDARD_SOURCE_SHA256 = "ff3bca80772f463a9baa3704f14572050d16a6dec831e894999c742084a9192e"
PINS = {
    "material_color_utilities": ("0.13.0", "9c337007e82b1889149c82ed242ed1cb24a66044e30979c44912381e9be4c48b"),
    "collection": ("1.19.1", "2f5709ae4d3d59dd8f7cd309b4e023046b57d8a6c82130785d2b0e5868084e76"),
}
ROLES = ("surface", "bright", "dim", "lowest", "low", "container", "high", "highest")
LITE = Path(__file__).resolve().parents[1]
TARGET = LITE / "app/src/androidTest/java/dev/aerove/lite/ui/FullPaletteSourceGoldens.kt"
DART_REFERENCE = r"""import 'dart:math';
import 'dart:convert';
import 'package:material_color_utilities/material_color_utilities.dart';
void main() {
 final output=<Map<String,Object?>>[];
 for(final seedArgb in [0xffffff00,0xffd8c0c3,0xff03a9f4,0xffe91e63,0xff007aff]) for(final dark in [false,true]) for(final tinted in [false,true]) {
  final seed=Hct.fromInt(seedArgb);
  final scheme=SchemeContent(sourceColorHct:seed,isDark:dark,contrastLevel:0);
  final tint=tinted?min(seed.chroma/6.0,10.0):null;
  final roles=<String,(DynamicColor,double,double?)>{
   'surface':(MaterialDynamicColors.surface,dark?3.0:1.5,null),
   'bright':(MaterialDynamicColors.surfaceBright,dark?3.0:1.5,null),
   'dim':(MaterialDynamicColors.surfaceDim,3.0,null),
   'lowest':(MaterialDynamicColors.surfaceContainerLowest,3.0,null),
   'low':(MaterialDynamicColors.surfaceContainerLow,3.0,null),
   'container':(MaterialDynamicColors.surfaceContainer,3.0,15.0),
   'high':(MaterialDynamicColors.surfaceContainerHigh,3.0,21.0),
   'highest':(MaterialDynamicColors.surfaceContainerHighest,3.0,27.0),
  };
  for(final entry in roles.entries){final (role,maxChroma,darkTone)=entry.value;final palette=role.palette(scheme);final tone=(dark?darkTone:null)??role.getTone(scheme);final color=Hct.from(palette.hue,tint??min(palette.chroma,maxChroma),tone);output.add({'seed':seedArgb.toRadixString(16),'dark':dark,'tinted':tinted,'role':entry.key,'argb':color.toInt().toRadixString(16),'chroma':color.chroma,'tone':color.tone,'requestedChroma':tint??min(palette.chroma,maxChroma)});}
 }
 print(jsonEncode(output));
}
"""


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def package_inputs(standard_root, pub_cache):
    source = standard_root / "lib/ui/color.dart"
    if sha256(source) != STANDARD_SOURCE_SHA256:
        raise ValueError("Standard color.dart changed; review the reference before regenerating")
    lock = (standard_root / "pubspec.lock").read_text(encoding="utf-8")
    config, inputs = [], [{"path": str(source), "sha256": sha256(source)}]
    for name, (version, archive_sha) in PINS.items():
        block = re.search(rf"^  {name}:\n(.*?)(?=^  \S|\Z)", lock, re.M | re.S)
        if not block or f'version: "{version}"' not in block[1] or archive_sha not in block[1]:
            raise ValueError(f"Standard dependency pin changed: {name}")
        archive_hash = pub_cache / f"hosted-hashes/pub.dev/{name}-{version}.sha256"
        if archive_hash.read_text(encoding="utf-8").strip() != archive_sha:
            raise ValueError(f"Cached archive pin differs: {name}")
        package = (pub_cache / f"hosted/pub.dev/{name}-{version}").resolve()
        config.append({"name": name, "rootUri": package.as_uri() + "/", "packageUri": "lib/", "languageVersion": "3.4"})
        inputs.extend({"path": str(path), "sha256": sha256(path)} for path in sorted((package / "lib").rglob("*.dart")))
    return config, inputs


def golden_contents(rows):
    cases = {}
    for row in rows:
        key = row["seed"], row["dark"], row["tinted"]
        roles = cases.setdefault(key, {})
        if row["role"] in roles:
            raise ValueError("Duplicate source role")
        roles[row["role"]] = row["argb"]
    if len(rows) != 160 or len(cases) != 20 or any(set(roles) != set(ROLES) for roles in cases.values()):
        raise ValueError("Incomplete Standard role output")
    lines = []
    for (seed, dark, tinted), roles in cases.items():
        colors = ", ".join(f"0x{roles[role]}.toInt()" for role in ROLES)
        style = "Tinted" if tinted else "Vivid"
        lines.append(f"    StandardSurfaceGolden(0x{seed}.toInt(), {str(dark).lower()}, ColorStyle.{style}, intArrayOf({colors})),")
    return (
        "package dev.aerove.lite.ui\n\nimport dev.aerove.lite.ColorStyle\n\n"
        "// Generated by tool/generate_palette_goldens.py from pinned Standard Dart MCU 0.13.0.\n"
        "internal data class StandardSurfaceGolden(val seed: Int, val dark: Boolean, val style: ColorStyle, val argb: IntArray)\n\n"
        "internal val standardSurfaceGoldens = listOf(\n" + "\n".join(lines) + "\n)\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--standard-root", required=True, type=Path)
    parser.add_argument("--pub-cache", required=True, type=Path)
    parser.add_argument("--dart", required=True, type=Path)
    parser.add_argument("--work-dir", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    config, inputs = package_inputs(args.standard_root.resolve(), args.pub_cache.resolve())
    work = args.work_dir.resolve()
    work.mkdir(parents=True, exist_ok=True)
    package_config, reference = work / "package_config.json", work / "standard-neutral-reference.dart"
    package_config.write_text(json.dumps({"configVersion": 2, "packages": config}, indent=2) + "\n", encoding="utf-8")
    reference.write_text(DART_REFERENCE, encoding="utf-8")
    command = [str(args.dart.resolve()), f"--packages={package_config}", str(reference)]
    result = subprocess.run(command, check=True, capture_output=True, text=True, encoding="utf-8")
    rows = json.loads(result.stdout)
    reference_json = work / "standard-neutral-reference.json"
    reference_json.write_text(result.stdout, encoding="utf-8")
    expected = golden_contents(rows).encode("utf-8")
    if args.check:
        if TARGET.read_bytes() != expected:
            raise ValueError("Generated palette goldens differ")
    else:
        TARGET.write_bytes(expected)
    provenance = {"command": command, "inputs": inputs, "sourceSha256": STANDARD_SOURCE_SHA256,
                  "pins": PINS, "generatorSha256": sha256(Path(__file__)), "referenceSha256": sha256(reference_json),
                  "targetSha256": hashlib.sha256(expected).hexdigest(), "cases": 20, "roles": 160, "check": args.check}
    (work / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n", encoding="utf-8")
    print(f"Palette goldens {'match' if args.check else 'generated'}: 20 cases / 160 roles")


if __name__ == "__main__":
    main()
